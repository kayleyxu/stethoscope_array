    'VariableNames',{'Statistic','Error_cm'});

fprintf('\nLOCALIZATION ERROR STATISTICS\n');
disp(statistics_table);

results_csv = fullfile( ...
    results_dir,'localization_results.csv');

results_mat = fullfile( ...
    results_dir,'localization_results.mat');

writetable(results_table,results_csv);

