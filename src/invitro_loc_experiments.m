function [predicted_position,maximum_score,score,best_index] = ...
    srp_das_fast_circular( ...
        signal_matrix,grid_positions,grid_delay_samples)
% Exact fast equivalent of:
%
%   combined = 0;
%   for mic = 1:M
%       combined = combined + ...
%           circshift(signal_matrix(:,mic),-delay(mic));
%   end
%   score = sum(combined.^2);
%
% Pairwise circular correlations avoid explicit shifting at every grid
% point while producing the same energy score.

    signal_matrix = double(signal_matrix);

    [num_samples,num_mics] = size(signal_matrix);

    num_grid_points = size(grid_positions,1);

    spectrum = fft(signal_matrix,num_samples,1);

    constant_energy = sum(signal_matrix(:).^2);

    score = constant_energy*ones(num_grid_points,1);

    for mic_a = 1:num_mics-1
        for mic_b = mic_a+1:num_mics
            circular_correlation = real(ifft( ...
                conj(spectrum(:,mic_a)).* ...
                spectrum(:,mic_b)));

            relative_lag = ...
                grid_delay_samples(:,mic_b)- ...
                grid_delay_samples(:,mic_a);

            correlation_index = ...
                mod(relative_lag,num_samples)+1;

            score = score+ ...
                2*circular_correlation(correlation_index);
        end
    end

    [maximum_score,best_index] = max(score);

    predicted_position = ...
        grid_positions(best_index,:);
end

function [predicted_position,maximum_score] = ...
    srp_das_literal_circshift( ...
        signal_matrix,grid_positions,grid_delay_samples)
% Slow literal implementation used only for optional verification.

    signal_matrix = double(signal_matrix);

    [num_samples,num_mics] = size(signal_matrix);
    num_grid_points = size(grid_positions,1);

    score = zeros(num_grid_points,1);

    for grid_idx = 1:num_grid_points
        combined_signal = zeros(num_samples,1);

        for mic = 1:num_mics
            delay = grid_delay_samples(grid_idx,mic);

            shifted_signal = circshift( ...
                signal_matrix(:,mic),-delay);

            combined_signal = ...
                combined_signal+shifted_signal;
        end

        score(grid_idx) = ...
            sum(combined_signal.^2);
    end

    [maximum_score,best_index] = max(score);

    predicted_position = ...
        grid_positions(best_index,:);
end
