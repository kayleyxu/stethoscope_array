    'total_error_cm', ...
    'x_error_cm', ...
    'y_error_cm', ...
    'z_error_cm', ...
    'mic_positions', ...
    'Fs','c', ...
    'localization_window_s');

fprintf('Mean total error:   %.2f cm\n',mean_error_cm);

fprintf('Median total error: %.2f cm\n',median(total_error_cm));

fprintf('RMSE:               %.2f cm\n',rmse_error_cm);

fprintf('Standard deviation: %.2f cm\n',std_error_cm);

fprintf('Maximum total error: %.2f cm\n',max(total_error_cm));

fprintf('Full results CSV:\n  %s\n',results_csv);
fprintf('Paper table CSV:\n  %s\n',paper_results_csv);
fprintf('Statistics CSV:\n  %s\n',statistics_csv);
fprintf('Results MAT:\n  %s\n',results_mat);

