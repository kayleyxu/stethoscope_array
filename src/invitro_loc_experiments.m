% invitro_loc_experiments.m
%
% Standalone analysis program for eight five-microphone recordings:
%
%   ..\data\localization_test1
%   ...
%   ..\data\localization_test8
%
% For each set, this program:
%   1. Reads audio_opt0.raw through audio_opt4.raw.
%   2. Uses the measured reference source location listed below.
%   3. Runs SRP-DAS over a 3-D search grid.
%   4. Reports predicted x, y, z, total error, and component errors.
%   5. Saves a CSV/MAT summary and several figures.
%
% Assumptions:
%   Fs = 64 kHz
%   c  = 30 m/s
%   RAW format = int16, little-endian
%
% -------------------------------------------------------------------------

clear;
close all;
clc;

%% ========================================================================
% SETTINGS
% =========================================================================
Fs = 64000;
c = 30;

num_sets = 8;
num_mics = 5;

machine_format = 'ieee-le';

data_parent = fullfile('..','data');

set_names = arrayfun( ...
    @(k) sprintf('localization_test%d',k), ...
    1:num_sets, ...
    'UniformOutput',false);

results_dir = fullfile( ...
    data_parent,'localization_analysis_results');

if ~exist(results_dir,'dir')
    mkdir(results_dir);
end

% Use the pulse-centered interval in each one-second recording.
localization_window_s = [0.45,0.56];

% Remove each channel's mean over the localization interval.
remove_window_dc = true;

% Normalize each channel by its RMS before SRP-DAS.
%
% false preserves the physical amplitude differences among microphones.
% true prevents one high-amplitude channel from dominating the score.
normalize_channels_by_rms = false;

% Optional literal circshift verification for one set. This is slow.
verify_fast_score_with_literal_loop = false;
literal_verification_set = 1;

% Plot one five-channel waveform figure per set.
plot_waveforms = true;

% Save figures as PNG.
save_figures = true;

%% ========================================================================
% REFERENCE ACTUAL SOURCE LOCATIONS
% =========================================================================
% Coordinates are in meters.
actual_positions = [
     0.01   0.10   0.063   % Recording 1
    -0.03   0.04   0.063   % Recording 2
    -0.05   0.00   0.063   % Recording 3
    -0.06   0.06   0.063   % Recording 4
     0.03   0.03   0.063   % Recording 5
     0.00   0.08   0.063   % Recording 6
    -0.01   0.04   0.042   % Recording 7
    -0.01   0.08   0.042   % Recording 8
];

clinical_lung_field = [
    "Upper-central"
    "Middle-central"
    "Lower-lateral"
    "Middle-lateral"
    "Middle-medial"
    "Upper-central"
    "Middle-central"
    "Upper-central"
];

relative_depth = [
    "Deeper"
    "Deeper"
    "Deeper"
    "Deeper"
    "Deeper"
    "Deeper"
    "Shallower"
    "Shallower"
];

assert(size(actual_positions,1) == num_sets, ...
    'actual_positions must contain eight rows.');
assert(numel(clinical_lung_field) == num_sets, ...
    'clinical_lung_field must contain eight entries.');
assert(numel(relative_depth) == num_sets, ...
    'relative_depth must contain eight entries.');

%% ========================================================================
% FIVE-MICROPHONE ARRAY GEOMETRY
% =========================================================================
% Each COLUMN is one microphone position, in meters.
mic_positions = [
    -7   -1    0
    -4    8    0
    -1    2    0
     2    5    0
     5   11    0
]'/100;

assert(size(mic_positions,2) == num_mics, ...
    'mic_positions must contain five columns.');

%% ========================================================================
% 3-D SRP-DAS SEARCH GRID
% =========================================================================
x_scan = linspace(-0.12,0.05,50);
y_scan = linspace(-0.01,0.11,50);

% Include the reference 4.2 cm and 6.3 cm source depths exactly.
z_scan = unique(sort([ ...
    linspace(0.02,0.10,50), ...
    0.042, ...
    0.063 ...
]));

[X_grid,Y_grid,Z_grid] = ndgrid( ...
    x_scan,y_scan,z_scan);

grid_positions = [ ...
    X_grid(:), ...
    Y_grid(:), ...
    Z_grid(:) ...
];

num_grid_points = size(grid_positions,1);

fprintf('\nPrecomputing delays for %d grid points...\n', ...
    num_grid_points);

grid_delay_samples = zeros( ...
    num_grid_points,num_mics);

for mic = 1:num_mics
    displacement = ...
        grid_positions-mic_positions(:,mic)';

    distance = sqrt(sum(displacement.^2,2));

    grid_delay_samples(:,mic) = ...
        round(distance*Fs/c);
end

%% ========================================================================
% RESULT STORAGE
% =========================================================================
predicted_positions = zeros(num_sets,3);

total_error_cm = zeros(num_sets,1);
x_error_cm = zeros(num_sets,1);
y_error_cm = zeros(num_sets,1);
z_error_cm = zeros(num_sets,1);

maximum_srp_score = zeros(num_sets,1);
score_contrast = zeros(num_sets,1);

window_start_s = zeros(num_sets,1);
window_end_s = zeros(num_sets,1);


waveform_cells = cell(num_sets,1);

%% ========================================================================
% READ AND LOCALIZE EACH RECORDING
% =========================================================================
for set_idx = 1:num_sets

    set_dir = fullfile( ...
        data_parent,set_names{set_idx});

    assert(exist(set_dir,'dir') == 7, ...
        'Could not find folder: %s',set_dir);

    fprintf('\n============================================================\n');
    fprintf('ANALYZING RECORDING %d: %s\n',set_idx,set_dir);
    fprintf('============================================================\n');

    %% Read all five microphones.
    channel_audio = cell(num_mics,1);
    common_num_samples = inf;

    for mic = 0:num_mics-1
        input_file = fullfile( ...
            set_dir,sprintf('audio_opt%d.raw',mic));

        fid = fopen(input_file,'rb',machine_format);
        assert(fid >= 0,'Could not open %s',input_file);

        x = fread(fid,inf,'int16=>double');
        fclose(fid);

        channel_audio{mic+1} = x(:);

        common_num_samples = min( ...
            common_num_samples,numel(x));
    end

    assert(common_num_samples > 0, ...
        'Set %d contains empty RAW files.',set_idx);

    signal_matrix = zeros( ...
        common_num_samples,num_mics);

    for mic = 1:num_mics
        signal_matrix(:,mic) = ...
            channel_audio{mic}(1:common_num_samples);
    end

    recording_duration_s = ...
        common_num_samples/Fs;

    assert(localization_window_s(1) >= 0 && ...
           localization_window_s(2) <= recording_duration_s, ...
        ['Localization window %.3f-%.3f s is outside Set %d ' ...
         'duration %.3f s.'], ...
        localization_window_s(1), ...
        localization_window_s(2), ...
        set_idx, ...
        recording_duration_s);

    first_sample = ...
        round(localization_window_s(1)*Fs)+1;

    last_sample = ...
        round(localization_window_s(2)*Fs);

    localization_matrix = ...
        signal_matrix(first_sample:last_sample,:);

    if remove_window_dc
        localization_matrix = ...
            localization_matrix-mean(localization_matrix,1);
    end

    if normalize_channels_by_rms
        channel_rms = sqrt(mean( ...
            localization_matrix.^2,1));

        channel_rms(channel_rms <= 0) = 1;

        localization_matrix = ...
            localization_matrix./channel_rms;
    end

    waveform_cells{set_idx} = ...
        localization_matrix;

    window_start_s(set_idx) = ...
        (first_sample-1)/Fs;

    window_end_s(set_idx) = ...
        (last_sample-1)/Fs;

    %% Run SRP-DAS.
    [predicted_position,best_score,all_scores,best_index] = ...
        srp_das_fast_circular( ...
            localization_matrix, ...
            grid_positions, ...
            grid_delay_samples);

    predicted_positions(set_idx,:) = ...
        predicted_position;

    maximum_srp_score(set_idx) = ...
        best_score;

    sorted_scores = sort(all_scores,'descend');

    if numel(sorted_scores) >= 2 && ...
            abs(sorted_scores(1)) > eps

        score_contrast(set_idx) = ...
            (sorted_scores(1)-sorted_scores(2))/ ...
            abs(sorted_scores(1));
    else
        score_contrast(set_idx) = 0;
    end

    %% Compute localization errors.
    error_vector_cm = ...
        100*(predicted_position- ...
             actual_positions(set_idx,:));

    x_error_cm(set_idx) = ...
        error_vector_cm(1);

    y_error_cm(set_idx) = ...
        error_vector_cm(2);

    z_error_cm(set_idx) = ...
        error_vector_cm(3);

    total_error_cm(set_idx) = ...
        norm(error_vector_cm);

    fprintf('Reference:    [%.4f %.4f %.4f] m\n', ...
        actual_positions(set_idx,:));

    fprintf('Estimated: [%.4f %.4f %.4f] m\n', ...
        predicted_position);

    fprintf(['Errors: x = %+0.3f cm, y = %+0.3f cm, ' ...
             'z = %+0.3f cm, total = %.3f cm\n'], ...
        x_error_cm(set_idx), ...
        y_error_cm(set_idx), ...
        z_error_cm(set_idx), ...
        total_error_cm(set_idx));

    fprintf('Best grid index: %d\n',best_index);

    %% Optional literal verification.
    if verify_fast_score_with_literal_loop && ...
            set_idx == literal_verification_set

        [literal_position,literal_score] = ...
            srp_das_literal_circshift( ...
                localization_matrix, ...
                grid_positions, ...
                grid_delay_samples);

        fprintf('\nLiteral-loop verification:\n');
        fprintf('Literal estimate: [%.5f %.5f %.5f] m\n', ...
            literal_position);
        fprintf('Fast estimate:    [%.5f %.5f %.5f] m\n', ...
            predicted_position);
        fprintf('Literal score: %.12g\n',literal_score);
        fprintf('Fast score:    %.12g\n',best_score);

        assert(norm(literal_position-predicted_position) < 1e-12, ...
            'Fast and literal SRP-DAS predicted different grid points.');
    end
end

